    private static void P(string region, string name, double lat, double lon, params string[] extra)
    {
        var p = new Place { Name = name, RegionId = region, Pos = new(lat, lon) };
        var forms = new HashSet<string>(StringComparer.Ordinal);
        var n = Normalize(name);
        if (n.Contains(' ')) forms.Add(n);
        else foreach (var f in Noun(n)) forms.Add(f);
        foreach (var e in extra) forms.Add(Normalize(e));
        foreach (var f in forms) p.Forms.Add(f.Split(' ', StringSplitOptions.RemoveEmptyEntries));
        Places.Add(p);
    }

