    private static IEnumerable<string> AdjF(string stem) => [stem + "ая", stem + "ой", stem + "ую", stem + "ие", stem + "их"];
    private static IEnumerable<string> AdjM(string stem) => [stem + "ий", stem + "ого", stem + "ом", stem + "ому", stem + "ый"];

    private static IEnumerable<string> Noun(string w)
    {
        if (w.Contains(' ') || w.Contains('-')) return [w];
        if (w.EndsWith('а')) { var s = w[..^1]; return [w, s + "ы", s + "и", s + "е", s + "у", s + "ой"]; }
        if (w.EndsWith('я')) { var s = w[..^1]; return [w, s + "и", s + "е", s + "ю", s + "ей"]; }
        if (w.EndsWith('ь')) { var s = w[..^1]; return [w, s + "и", s + "ью", s + "я", s + "ю", s + "е"]; }
        if (w.EndsWith('й')) { var s = w[..^1]; return [w, s + "я", s + "ю", s + "е", s + "ем"]; }
        if (w.EndsWith('ы')) { var s = w[..^1]; return [w, s + "ов", s + "ах", s + "ам"]; }
        if (w.EndsWith('о') || w.EndsWith('е') || w.EndsWith('и') || w.EndsWith('у')) return [w];
        return [w, w + "а", w + "у", w + "е", w + "ом"];
    }

    private static void R(string id, string name, double lat, double lon, string? polygon, IEnumerable<string> words,
        double halfLat = 1.6, double halfLon = 2.6)
    {
        var r = new Region { Id = id, Name = name, Center = new(lat, lon), PolygonQuery = polygon, HalfLat = halfLat, HalfLon = halfLon };
        foreach (var w in words) r.Words.Add(Normalize(w));
        Regions[id] = r;
    }

