using Radar.Models;

namespace Radar.Services;

public sealed class Region
{
    public required string Id { get; init; }
    public required string Name { get; init; }
    public required GeoPoint Center { get; init; }
    public double HalfLat { get; init; } = 1.6;
    public double HalfLon { get; init; } = 2.6;
    /// <summary>Запрос к Nominatim для получения границы; null — граница не рисуется.</summary>
    public string? PolygonQuery { get; init; }
    public HashSet<string> Words { get; } = new(StringComparer.Ordinal);

    public (double MinLat, double MinLon, double MaxLat, double MaxLon) DefaultBox =>
        (Center.Lat - HalfLat, Center.Lon - HalfLon, Center.Lat + HalfLat, Center.Lon + HalfLon);
}

public sealed class Place
{
    public required string Name { get; init; }
    public required string RegionId { get; init; }
    public required GeoPoint Pos { get; init; }
    public List<string[]> Forms { get; } = [];
    public bool Ambiguous { get; set; }
}

/// <summary>Встроенный справочник регионов и часто упоминаемых населённых пунктов.</summary>
public static class Gazetteer
{
    public static readonly Dictionary<string, Region> Regions = new(StringComparer.Ordinal);
    public static readonly List<Place> Places = [];
    private static readonly Dictionary<string, List<Place>> PlacesByFirstToken = new(StringComparer.Ordinal);
    private static readonly Dictionary<string, List<string>> RegionByWord = new(StringComparer.Ordinal);

    static Gazetteer()
    {
        BuildRegions();
        BuildPlaces();
        foreach (var r in Regions.Values)
            foreach (var w in r.Words)
            {
                if (!RegionByWord.TryGetValue(w, out var list)) RegionByWord[w] = list = [];
                if (!list.Contains(r.Id)) list.Add(r.Id);
            }

        var nameCount = Places.GroupBy(p => p.Name).ToDictionary(g => g.Key, g => g.Count());
        foreach (var p in Places)
        {
            p.Ambiguous = nameCount[p.Name] > 1 || p.Ambiguous;
            foreach (var f in p.Forms)
            {
                if (!PlacesByFirstToken.TryGetValue(f[0], out var list)) PlacesByFirstToken[f[0]] = list = [];
                list.Add(p);
            }
        }
    }

    public static bool IsRegionWord(string token) => RegionByWord.ContainsKey(token);
    public static IReadOnlyList<string> RegionsForWord(string token) =>
        RegionByWord.TryGetValue(token, out var l) ? l : [];

    public static Region? Get(string? id) => id != null && Regions.TryGetValue(id, out var r) ? r : null;

    /// <summary>Регион вне РФ (только источник/направление угрозы).</summary>
    public static bool IsForeign(string id) => id.StartsWith("ua_", StringComparison.Ordinal);

    /// <summary>Находит все упоминания известных населённых пунктов в токенизированном тексте.</summary>
    public static IEnumerable<(Place Place, int Index, int Length)> FindPlaces(IReadOnlyList<string> tokens)
    {
        for (int i = 0; i < tokens.Count; i++)
        {
            if (!PlacesByFirstToken.TryGetValue(tokens[i], out var candidates)) continue;
            foreach (var p in candidates)
                foreach (var f in p.Forms)
                {
                    if (f[0] != tokens[i] || i + f.Length > tokens.Count) continue;
                    bool ok = true;
                    for (int k = 1; k < f.Length && ok; k++) ok = tokens[i + k] == f[k];
                    if (ok) yield return (p, i, f.Length);
                }
        }
    }

    // латинская «ë» (U+00EB) встречается вместо «ё» при наборе с чужой раскладки («Новые Ивайтëнки»)
    public static string Normalize(string s) => s.ToLowerInvariant().Replace('ё', 'е').Replace('ë', 'е');

    /// <summary>Убирает ударения (U+0301), разложенную «ё» (е+U+0308 → е) и мягкие переносы (U+00AD), которые рвут слово.</summary>
    public static string StripMarks(string s)
    {
        foreach (var c in s)
            if (IsIgnorable(c)) return string.Concat(s.Normalize(System.Text.NormalizationForm.FormC).Where(ch => !IsIgnorable(ch)));
        return s;
    }

    public static bool IsIgnorable(char c) => c >= '\u0300' && (char.GetUnicodeCategory(c) is System.Globalization.UnicodeCategory.NonSpacingMark
        or System.Globalization.UnicodeCategory.Format);

    /// <summary>Токен с исходным регистром и признаком «перед ним был разделитель» (запятая, точка, перевод строки, «|»).</summary>
    /// <remarks><paramref name="Hard"/> — перед токеном конец строки или предложения (не запятая).</remarks>
    public readonly record struct RawToken(string Lower, string Orig, bool Break, bool Hard = false);

    /// <summary>Токенизация, совпадающая по индексам с <see cref="Tokenize"/>, но с исходным регистром и разделителями.</summary>
    public static List<RawToken> TokenizeRaw(string text)
    {
        var tokens = new List<RawToken>();
        var sb = new System.Text.StringBuilder();
        bool brk = true, pendingBreak = true, hard = true, pendingHard = true;
        foreach (var ch in text)
        {
            var lc = char.ToLowerInvariant(ch) == 'ё' ? 'е' : char.ToLowerInvariant(ch);
            if (char.IsLetterOrDigit(lc) || (lc == '-' && sb.Length > 0)) { if (sb.Length == 0) { brk = pendingBreak; hard = pendingHard; } sb.Append(ch); }
            else
            {
                Flush();
                if (!char.IsWhiteSpace(ch) || ch == '\n') pendingBreak = true;
                if (ch is '\n' or '.' or '|' or '!' or '?' or ';') pendingHard = true;
            }
        }
        Flush();
        return tokens;

        void Flush()
        {
            if (sb.Length == 0) return;
            var orig = sb.ToString().Trim('-');
            tokens.Add(new RawToken(Normalize(orig), orig, brk, hard));
            sb.Clear();
            pendingBreak = false;
            pendingHard = false;
        }
    }

    public static List<string> Tokenize(string text)
    {
        var tokens = new List<string>();
        var sb = new System.Text.StringBuilder();
        foreach (var ch0 in Normalize(text))
        {
            if (char.IsLetterOrDigit(ch0) || (ch0 == '-' && sb.Length > 0)) sb.Append(ch0);
            else Flush();
        }
        Flush();
        return tokens;

        void Flush()
        {
            if (sb.Length == 0) return;
            tokens.Add(sb.ToString().Trim('-'));
            sb.Clear();
        }
    }

